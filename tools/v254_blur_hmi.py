def blur(box, r):
    x0,y0,x1,y1 = box
    p = 4
    bx = (max(0,x0-p), max(0,y0-p), min(im.width,x1+p), min(im.height,y1+p))
    region = im.crop(bx).filter(ImageFilter.GaussianBlur(r)).filter(ImageFilter.GaussianBlur(r))
    mask = Image.new('L', region.size, 0)
    ImageDraw.Draw(mask).rectangle((x0-bx[0], y0-bx[1], x1-bx[0], y1-bx[1]), fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(2))
    im.paste(region, bx, mask)
